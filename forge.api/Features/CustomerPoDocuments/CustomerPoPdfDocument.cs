using Forge.Api.Services;
using Forge.Api.Services.Pdf;
using Forge.Core.Entities;
using Forge.Core.Models;

namespace Forge.Api.Features.CustomerPoDocuments;

/// <summary>
/// S4a — internally-generated customer purchase-order record. Structural
/// clone of <see cref="Forge.Api.Features.Invoices.InvoicePdfDocument"/>.
/// The document renders LIVE from the linked sales order (the entity passed
/// in must have SalesOrder → Customer / Lines→Part / ShippingAddress loaded),
/// and is clearly labeled as an internal record referencing the Forge SO
/// number — it is NOT a customer-supplied document.
/// </summary>
public static class CustomerPoPdfDocument
{
    private const string Styles = """
        .head .internal { font-size: 8pt; color: #757575; }
        .banner { margin-top: 6pt; padding: 6pt; background: #f5f5f5; font-size: 8pt; font-style: italic; color: #616161; }
        .parties .ship-to { margin-top: 4pt; }
        .disclaimer { position: fixed; left: 0; right: 0; bottom: -16pt; font-size: 8pt; color: #9e9e9e; text-align: center; }
        """;

    public static HtmlPdfDocument Build(CustomerPoDocument document, string? companyName, MoneyFormatter? money = null)
    {
        money ??= MoneyFormat.For(null, "USD");
        var order = document.SalesOrder;

        var body = Html.Of($"{Disclaimer(order)}{Header(document, order, companyName)}{Lines(order, money)}{Totals(order, money)}{Notes(order)}");
        return PdfHtml.Document($"Purchase Order {document.DocumentNumber}", body, document.DocumentNumber, styles: Styles);
    }

    private static Html Disclaimer(SalesOrder order)
        => Html.Of($"<div class=\"disclaimer\">Internal document generated by Forge from sales order {order.OrderNumber} — not a customer-issued purchase order.</div>");

    private static Html Header(CustomerPoDocument document, SalesOrder order, string? companyName)
    {
        var customer = order.Customer;
        return Html.Of($"""
            <div class="head">
              <div class="company">{companyName}</div>
              <div class="right">
                <div class="title">PURCHASE ORDER</div>
                <div class="number">#{document.DocumentNumber}</div>
                <div class="internal">Internal record — auto-generated</div>
              </div>
            </div>
            <div class="banner">Internally-generated purchase order record for Forge sales order {order.OrderNumber}. Contents render live from the current sales order.</div>
            <hr class="rule">
            <div class="parties">
              <div>
                <div class="label">Customer:</div>
                <div class="strong">{customer.CompanyName ?? customer.Name}</div>
                {(string.IsNullOrEmpty(customer.Email) ? Html.Empty : Html.Of($"<div class=\"small\">{customer.Email}</div>"))}
                {(string.IsNullOrEmpty(customer.Phone) ? Html.Empty : Html.Of($"<div class=\"small\">{customer.Phone}</div>"))}
                {ShipTo(order.ShippingAddress)}
              </div>
              <div class="right">
                <div>Generated: {document.GeneratedAt:MM/dd/yyyy}</div>
                <div>SO #: {order.OrderNumber}</div>
                <div>SO Status: {order.Status}</div>
                {(string.IsNullOrEmpty(order.CustomerPO) ? Html.Empty : Html.Of($"<div>Customer PO Ref: {order.CustomerPO}</div>"))}
                {(string.IsNullOrEmpty(document.GeneratedFromQuote?.QuoteNumber) ? Html.Empty : Html.Of($"<div>Quote #: {document.GeneratedFromQuote.QuoteNumber}</div>"))}
              </div>
            </div>
            """);
    }

    private static Html ShipTo(CustomerAddress? address)
    {
        if (address is null)
            return Html.Empty;

        return Html.Of($"""
            <div class="label ship-to">Ship To:</div>
            <div class="small">{address.Line1}</div>
            {(string.IsNullOrWhiteSpace(address.Line2) ? Html.Empty : Html.Of($"<div class=\"small\">{address.Line2}</div>"))}
            <div class="small">{address.City}, {address.State} {address.PostalCode}</div>
            """);
    }

    private static Html Lines(SalesOrder order, MoneyFormatter money)
    {
        var rows = order.Lines
            .OrderBy(l => l.LineNumber)
            .Select(line => Html.Of($"""
                <tr>
                  <td>{line.LineNumber}</td>
                  <td>{line.Description}</td>
                  <td>{line.Part?.PartNumber ?? "—"}</td>
                  <td class="num">{MoneyFormat.Quantity(line.Quantity)}</td>
                  <td class="num">{money.Format(line.UnitPrice)}</td>
                  <td class="num">{money.Format(line.LineTotal)}</td>
                </tr>
                """));

        return Html.Of($"""
            <table class="lines">
              <colgroup><col style="width:40pt"><col><col style="width:80pt"><col style="width:60pt"><col style="width:80pt"><col style="width:90pt"></colgroup>
              <thead><tr><th>#</th><th>Description</th><th>Part #</th><th class="num">Qty</th><th class="num">Unit Price</th><th class="num">Total</th></tr></thead>
              <tbody>{rows}</tbody>
            </table>
            """);
    }

    private static Html Totals(SalesOrder order, MoneyFormatter money)
    {
        var rows = new List<Html>
        {
            Row("Subtotal:", money.Format(order.Subtotal), "strong-label"),
        };
        if (order.TaxRate > 0)
            rows.Add(Row($"Tax ({MoneyFormat.Percent(order.TaxRate)}):", money.Format(order.TaxAmount), "strong-label"));
        rows.Add(Row("Total:", money.Format(order.Total), "grand after-rule"));

        return Html.Of($"<div class=\"totals\">{rows}</div>");
    }

    private static Html Row(string label, string amount, string style)
        => Html.Of($"<div class=\"row {style}\"><span>{label}</span><span>{amount}</span></div>");

    private static Html Notes(SalesOrder order)
        => string.IsNullOrWhiteSpace(order.Notes)
            ? Html.Empty
            : Html.Of($"<div class=\"notes\"><div class=\"label\">Notes</div><div class=\"body\">{order.Notes}</div></div>");
}
