using System.Text.Json;

using Forge.Api.Services.Pdf;
using Forge.Core.Entities;
using Forge.Core.Models;

namespace Forge.Api.Features.ComplianceForms;

public static class ComplianceFormSubmissionPdfDocument
{
    private const string FooterLabel = "Generated by Forge";

    private const string Styles = """
        @page portrait { margin: 72pt 72pt 86pt; }
        .form-name { font-size: 16pt; font-weight: 600; }
        .submitted { font-size: 9pt; color: #9e9e9e; }
        .form-rule { border: 0; border-top: 1pt solid #e0e0e0; margin: 6pt 0 0; }
        .form-body { padding-top: 12pt; }
        .acknowledged { padding-top: 20pt; color: #9e9e9e; }
        .page-title { padding-top: 10pt; font-size: 12pt; font-weight: 600; }
        .section-title { padding-top: 14pt; padding-bottom: 2pt; font-size: 11pt; font-weight: 600; color: #1976d2; }
        .section-rule { border: 0; border-top: 0.5pt solid #e0e0e0; margin: 0; }
        .field { display: flex; align-items: flex-start; padding: 3pt 0; break-inside: avoid; }
        .field .name { width: 40%; padding-right: 8pt; font-size: 9pt; color: #616161; }
        .field .value { width: 60%; font-size: 10pt; white-space: pre-wrap; }
        """;

    private sealed record ParsedField(string Id, string Label, string Type);
    private sealed record ParsedSection(string? Title, List<ParsedField> Fields);
    private sealed record ParsedPage(string? Title, List<ParsedSection> Sections);

    public static HtmlPdfDocument Build(ComplianceFormSubmission submission, DateTimeOffset now)
    {
        var formName = submission.Template?.Name ?? "Compliance Form";
        var submittedOn = submission.SignedAt?.ToString("MM/dd/yyyy") ?? now.ToString("MM/dd/yyyy");

        var formData = ParseFormData(submission.FormDataJson);
        var defJson = submission.FormDefinitionVersion?.FormDefinitionJson;
        var pages = string.IsNullOrEmpty(defJson) ? [] : ParsePages(defJson);

        var body = Html.Of($"""
            <div class="form-name">{formName}</div>
            <div class="submitted">Submitted: {submittedOn}</div>
            <hr class="form-rule">
            <div class="form-body">{Content(pages, formData)}</div>
            """);
        return PdfHtml.Document(formName, body, FooterLabel, styles: Styles);
    }

    private static Html Content(List<ParsedPage> pages, Dictionary<string, JsonElement> formData)
    {
        if (pages.Count == 0 || formData.Count == 0)
            return Html.Of($"<div class=\"acknowledged\">This form was acknowledged/completed electronically.</div>");

        var parts = new List<Html>();
        foreach (var pg in pages)
        {
            if (pages.Count > 1 && !string.IsNullOrEmpty(pg.Title))
                parts.Add(Html.Of($"<div class=\"page-title\">{pg.Title}</div>"));

            foreach (var section in pg.Sections)
            {
                var sectionHasValues = section.Fields.Any(f =>
                    !IsDisplayOnly(f.Type) && formData.ContainsKey(f.Id));

                if (!sectionHasValues) continue;

                if (!string.IsNullOrEmpty(section.Title))
                    parts.Add(Html.Of($"<div class=\"section-title\">{section.Title}</div>"));

                parts.Add(Html.Of($"<hr class=\"section-rule\">"));

                foreach (var field in section.Fields)
                {
                    if (IsDisplayOnly(field.Type)) continue;
                    if (!formData.TryGetValue(field.Id, out var val)) continue;

                    var display = GetDisplayValue(val, field.Type);
                    if (string.IsNullOrWhiteSpace(display)) continue;

                    parts.Add(Html.Of($"<div class=\"field\"><div class=\"name\">{field.Label}</div><div class=\"value\">{display}</div></div>"));
                }
            }
        }

        return Html.Join(parts);
    }

    private static Dictionary<string, JsonElement> ParseFormData(string? json)
    {
        if (string.IsNullOrEmpty(json)) return [];
        try
        {
            using var doc = JsonDocument.Parse(json);
            return doc.RootElement.EnumerateObject()
                .ToDictionary(p => p.Name, p => p.Value.Clone());
        }
        catch (JsonException)
        {
            return [];
        }
    }

    private static List<ParsedPage> ParsePages(string defJson)
    {
        try
        {
            using var doc = JsonDocument.Parse(defJson);
            var root = doc.RootElement;

            List<ParsedPage> pages = [];

            if (root.TryGetProperty("pages", out var pagesEl))
            {
                foreach (var pg in pagesEl.EnumerateArray())
                {
                    var title = pg.TryGetProperty("title", out var t) ? t.GetString() : null;
                    pages.Add(new ParsedPage(title, ParseSections(pg)));
                }
            }
            else if (root.TryGetProperty("sections", out var sectionsEl))
            {
                pages.Add(new ParsedPage(null, ParseSections(root)));
            }

            return pages;
        }
        catch (JsonException)
        {
            return [];
        }
    }

    private static List<ParsedSection> ParseSections(JsonElement parent)
    {
        List<ParsedSection> sections = [];
        if (!parent.TryGetProperty("sections", out var sectionsEl)) return sections;

        foreach (var sec in sectionsEl.EnumerateArray())
        {
            var title = sec.TryGetProperty("title", out var t) ? t.GetString() : null;
            List<ParsedField> fields = [];

            if (sec.TryGetProperty("fields", out var fieldsEl))
            {
                foreach (var field in fieldsEl.EnumerateArray())
                {
                    if (!field.TryGetProperty("id", out var idEl)) continue;
                    var id = idEl.GetString();
                    if (string.IsNullOrEmpty(id)) continue;

                    var label = field.TryGetProperty("label", out var lbl)
                        ? lbl.GetString() ?? id
                        : id;
                    var type = field.TryGetProperty("type", out var tp)
                        ? tp.GetString() ?? "text"
                        : "text";

                    fields.Add(new ParsedField(id, label, type));
                }
            }

            sections.Add(new ParsedSection(title, fields));
        }

        return sections;
    }

    private static bool IsDisplayOnly(string type) =>
        type is "heading" or "paragraph" or "html";

    private static string GetDisplayValue(JsonElement val, string fieldType) =>
        fieldType switch
        {
            "checkbox" or "toggle" =>
                val.ValueKind == JsonValueKind.True ? "Yes" :
                val.ValueKind == JsonValueKind.False ? "No" : "",
            _ => val.ValueKind switch
            {
                JsonValueKind.String => val.GetString() ?? "",
                JsonValueKind.True => "Yes",
                JsonValueKind.False => "No",
                JsonValueKind.Number => val.GetRawText(),
                _ => "",
            },
        };
}
