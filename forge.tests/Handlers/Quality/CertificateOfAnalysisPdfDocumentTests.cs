using System.Net;

using AwesomeAssertions;

using Forge.Api.Features.Quality.Coa;
using Forge.Core.Entities;
using Forge.Core.Enums;

namespace Forge.Tests.Handlers.Quality;

public class CertificateOfAnalysisPdfDocumentTests
{
    private static CertificateOfAnalysis Certificate(bool conforms = true, string? notes = null)
    {
        var certificate = new CertificateOfAnalysis
        {
            CertificateNumber = "COA-000042",
            Status = CertificateOfAnalysisStatus.Issued,
            Conforms = conforms,
            GeneratedAt = new DateTimeOffset(2026, 10, 1, 12, 0, 0, TimeSpan.Zero),
            Notes = notes,
            LotRecord = new LotRecord { LotNumber = "L-1001", Quantity = 12.5m, PartRevision = "B", SupplierLotNumber = "SUP-9" },
            Part = new Part { PartNumber = "RP-100", Name = "Resin pellet" },
            Customer = new Customer { Name = "Buyer Co" },
        };
        certificate.Results.Add(new CoaResult { SortOrder = 2, Characteristic = "Colour", Specification = "Natural", Result = "Natural", Pass = true });
        certificate.Results.Add(new CoaResult { SortOrder = 1, Characteristic = "Melt flow index", Specification = "10 ± 0.5", Result = "11.1", Unit = "g/10min", Pass = conforms });
        return certificate;
    }

    [Fact]
    public void Prints_the_lot_the_results_in_order_and_the_statement()
    {
        var html = WebUtility.HtmlDecode(CertificateOfAnalysisPdfDocument.Build(
            Certificate(conforms: false), "Harbor Plastics", "Inspector, Quinn", CertificateOfAnalysisPdfLabels.English).Html);

        html.Should().Contain("CERTIFICATE OF ANALYSIS").And.Contain("#COA-000042").And.Contain("Issued: 10/01/2026");
        html.Should().Contain("RP-100 — Resin pellet").And.Contain("L-1001").And.Contain("12.5").And.Contain("SUP-9");
        html.Should().Contain("Generated by: Inspector, Quinn");
        html.Should().Contain("does NOT conform").And.Contain(">Fail<");
        html.IndexOf("Melt flow index", StringComparison.Ordinal).Should().BeLessThan(html.IndexOf("Colour", StringComparison.Ordinal));
    }

    [Fact]
    public void Prints_in_spanish()
    {
        var html = WebUtility.HtmlDecode(CertificateOfAnalysisPdfDocument.Build(
            Certificate(), null, null, CertificateOfAnalysisPdfLabels.Spanish).Html);

        html.Should().Contain("CERTIFICADO DE ANÁLISIS").And.Contain("Pieza:").And.Contain("Resultado").And.Contain("Cumple");
        html.Should().NotContain("Pass/Fail");
    }

    [Fact]
    public void Encodes_every_value_a_user_typed()
    {
        var certificate = Certificate(notes: "</div><script>alert(1)</script>");
        certificate.Results.First().Characteristic = "Colour <b>bold</b>";

        var html = CertificateOfAnalysisPdfDocument.Build(
            certificate, "Harbor <Plastics>", "<b>Quinn</b>", CertificateOfAnalysisPdfLabels.English).Html;

        html.Should().NotContain("<script").And.NotContain("<b>");
        html.Should().Contain("Colour &lt;b&gt;bold&lt;/b&gt;").And.Contain("&lt;script&gt;").And.Contain("Harbor &lt;Plastics&gt;");
    }

    [Fact]
    public void The_footer_carries_the_certificate_number()
    {
        var html = CertificateOfAnalysisPdfDocument.Build(Certificate(), null, null, CertificateOfAnalysisPdfLabels.English).Html;

        html.Should().Contain("<div class=\"page-footer\">COA-000042 &middot; Page ");
    }
}
