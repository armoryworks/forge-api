using System.Net;

using AwesomeAssertions;
using Microsoft.Extensions.Logging.Abstractions;
using Moq;

using Forge.Api.Features.ComplianceForms;
using Forge.Core.Entities;
using Forge.Core.Interfaces;
using Forge.Data.Context;
using Forge.Integrations;
using Forge.Tests.Helpers;

namespace Forge.Tests.Handlers.ComplianceForms;

public class DownloadSubmissionPdfHandlerTests
{
    private const string Definition = """
        {
          "pages": [
            {
              "title": "Employee",
              "sections": [
                {
                  "title": "Personal details",
                  "fields": [
                    { "id": "intro", "label": "Read this", "type": "paragraph" },
                    { "id": "name", "label": "Full name", "type": "text" },
                    { "id": "agree", "label": "I agree", "type": "checkbox" },
                    { "id": "dependents", "label": "Dependents", "type": "number" },
                    { "id": "blank", "label": "Middle name", "type": "text" }
                  ]
                },
                { "title": "Unanswered", "fields": [ { "id": "other", "label": "Other", "type": "text" } ] }
              ]
            },
            { "title": "Employer", "sections": [] }
          ]
        }
        """;

    private static readonly DateTimeOffset Now = new(2026, 11, 2, 9, 0, 0, TimeSpan.Zero);

    private static ComplianceFormSubmission Submission(string formDataJson, string templateName = "W-4 Withholding", DateTimeOffset? signedAt = null) => new()
    {
        UserId = 5,
        SignedAt = signedAt,
        FormDataJson = formDataJson,
        Template = new ComplianceFormTemplate { Name = templateName },
        FormDefinitionVersion = new FormDefinitionVersion { FormDefinitionJson = Definition },
    };

    [Fact]
    public void Prints_each_answered_field_under_its_page_and_section()
    {
        var submission = Submission("""{"name":"Doe, Jane","agree":true,"dependents":2,"blank":"  "}""",
            signedAt: new DateTimeOffset(2026, 10, 15, 0, 0, 0, TimeSpan.Zero));

        var html = WebUtility.HtmlDecode(ComplianceFormSubmissionPdfDocument.Build(submission, Now).Html);

        html.Should().Contain("W-4 Withholding").And.Contain("Submitted: 10/15/2026");
        html.Should().Contain("<div class=\"page-title\">Employee</div>").And.Contain("Personal details");
        html.Should().Contain("Full name").And.Contain("Doe, Jane").And.Contain(">Yes<").And.Contain(">2<");
        html.Should().NotContain("Read this").And.NotContain("Middle name").And.NotContain("Unanswered");
    }

    [Fact]
    public void A_submission_with_no_data_reads_as_acknowledged()
    {
        var html = ComplianceFormSubmissionPdfDocument.Build(Submission(""), Now).Html;

        html.Should().Contain("This form was acknowledged/completed electronically.").And.Contain("Submitted: 11/02/2026");
    }

    [Fact]
    public void Encodes_every_value_a_user_typed()
    {
        var submission = Submission("""{"name":"<script>alert(1)</script><b>x</b>"}""", templateName: "Form <b>A</b>");

        var html = ComplianceFormSubmissionPdfDocument.Build(submission, Now).Html;

        html.Should().NotContain("<script").And.NotContain("<b>");
        html.Should().Contain("&lt;script&gt;alert(1)&lt;/script&gt;&lt;b&gt;x&lt;/b&gt;").And.Contain("Form &lt;b&gt;A&lt;/b&gt;");
    }

    [Fact]
    public void The_footer_says_who_generated_it()
    {
        var html = ComplianceFormSubmissionPdfDocument.Build(Submission(""), Now).Html;

        html.Should().Contain("<div class=\"page-footer\">Generated by Forge &middot; Page ");
    }

    [Fact]
    public async Task An_unsigned_submission_is_printed_through_the_renderer()
    {
        AppDbContext db = TestDbContextFactory.Create();
        var submission = Submission("""{"name":"Doe, Jane"}""", templateName: "W-4 / 2026");
        db.ComplianceFormSubmissions.Add(submission);
        await db.SaveChangesAsync();
        var renderer = new FakeHtmlPdfRenderer();
        var clock = new Mock<IClock>();
        clock.SetupGet(c => c.UtcNow).Returns(Now);
        var handler = new DownloadSubmissionPdfHandler(
            db, new MockStorageService(NullLogger<MockStorageService>.Instance), renderer, clock.Object);

        var result = await handler.Handle(new DownloadSubmissionPdfQuery(submission.Id, 5, false), CancellationToken.None);

        result.FileName.Should().Be("W-4 _ 2026.pdf");
        result.Bytes.Should().StartWith("%PDF-"u8.ToArray());
        renderer.Documents.Should().ContainSingle().Subject.Html.Should().Contain("Doe, Jane");
    }
}
