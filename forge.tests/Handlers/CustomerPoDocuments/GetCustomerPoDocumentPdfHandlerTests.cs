using AwesomeAssertions;
using Moq;

using Forge.Api.Features.CustomerPoDocuments;
using Forge.Core.Entities;
using Forge.Core.Interfaces;
using Forge.Tests.Helpers;

namespace Forge.Tests.Handlers.CustomerPoDocuments;

/// <summary>
/// S4a — PDF contract test (same shape as CustomerStatementContractTests):
/// the document builds against a representative live SO without throwing
/// and the renderer is handed it to print.
/// </summary>
public class GetCustomerPoDocumentPdfHandlerTests
{
    [Fact]
    public async Task PdfHandler_ProducesNonEmptyPdf_FromLiveSalesOrder()
    {
        using var db = TestDbContextFactory.Create();

        var customer = new Customer
        {
            Name = "PDF Contract Co",
            Email = "po@pdfco.example",
            Phone = "+1-555-0101",
        };
        db.Customers.Add(customer);
        await db.SaveChangesAsync();

        var address = new CustomerAddress
        {
            CustomerId = customer.Id,
            Label = "Dock 1",
            Line1 = "42 Shipping Lane",
            City = "Peoria",
            State = "IL",
            PostalCode = "61602",
        };
        db.CustomerAddresses.Add(address);
        await db.SaveChangesAsync();

        var order = new SalesOrder
        {
            OrderNumber = "SO-88001",
            CustomerId = customer.Id,
            ShippingAddressId = address.Id,
            CustomerPO = "PO-EXT-123",
            Notes = "Deliver to dock 1",
            TaxRate = 0.0875m,
        };
        order.Lines.Add(new SalesOrderLine { Description = "Bracket, welded", Quantity = 12, UnitPrice = 18.50m, LineNumber = 1 });
        order.Lines.Add(new SalesOrderLine { Description = "Machined shaft", Quantity = 3.5m, UnitPrice = 240m, LineNumber = 2 });
        db.SalesOrders.Add(order);
        await db.SaveChangesAsync();

        db.CustomerPoDocuments.Add(new CustomerPoDocument
        {
            SalesOrderId = order.Id,
            DocumentNumber = "CPO-00001",
            GeneratedAt = DateTimeOffset.UtcNow,
        });
        await db.SaveChangesAsync();

        var settings = new Mock<ISystemSettingRepository>();
        settings.Setup(s => s.FindByKeyAsync("company.name", It.IsAny<CancellationToken>()))
            .ReturnsAsync(new SystemSetting { Key = "company.name", Value = "Armory Works Test" });

        var renderer = new FakeHtmlPdfRenderer();
        var handler = new GetCustomerPoDocumentPdfHandler(db, settings.Object, renderer);

        var pdf = await handler.Handle(
            new GetCustomerPoDocumentPdfQuery(order.Id), CancellationToken.None);

        pdf.Should().StartWith("%PDF-"u8.ToArray());
        var html = renderer.Documents.Should().ContainSingle().Subject.Html;
        html.Should().Contain("PURCHASE ORDER").And.Contain("#CPO-00001").And.Contain("SO #: SO-88001")
            .And.Contain("Customer PO Ref: PO-EXT-123").And.Contain("42 Shipping Lane").And.Contain("Peoria, IL 61602")
            .And.Contain("8.75%").And.Contain("Deliver to dock 1");
        html.Should().Contain("<div class=\"page-footer\">CPO-00001 &middot; Page ");
        html.Should().Contain("Internal document generated by Forge from sales order SO-88001");
    }

    [Fact]
    public void Pdf_EncodesEveryValueAUserTyped()
    {
        var order = new SalesOrder
        {
            OrderNumber = "SO-88002",
            Customer = new Customer { Name = "<img src=x onerror=alert(1)>" },
            ShippingAddress = new CustomerAddress { Line1 = "<b>Dock</b>", City = "Peoria", State = "IL", PostalCode = "61602" },
            Notes = "</div><script>fetch('http://internal/')</script>",
        };
        order.Lines.Add(new SalesOrderLine { Description = "Bracket <b>bold</b>", Quantity = 1m, UnitPrice = 1m, LineNumber = 1 });
        var document = new CustomerPoDocument { SalesOrder = order, DocumentNumber = "CPO-00002", GeneratedAt = DateTimeOffset.UnixEpoch };

        var html = CustomerPoPdfDocument.Build(document, "Harbor <Gear> Works").Html;

        html.Should().NotContain("<img").And.NotContain("<script").And.NotContain("<b>");
        html.Should().Contain("&lt;img src=x onerror=alert(1)&gt;").And.Contain("Bracket &lt;b&gt;bold&lt;/b&gt;")
            .And.Contain("&lt;b&gt;Dock&lt;/b&gt;").And.Contain("Harbor &lt;Gear&gt; Works");
        html.Should().Contain("<div class=\"page-footer\">CPO-00002 &middot; Page ");
    }

    [Fact]
    public async Task PdfHandler_NoDocumentForOrder_ThrowsKeyNotFound()
    {
        using var db = TestDbContextFactory.Create();
        var settings = new Mock<ISystemSettingRepository>();
        var handler = new GetCustomerPoDocumentPdfHandler(db, settings.Object, new FakeHtmlPdfRenderer());

        var act = () => handler.Handle(
            new GetCustomerPoDocumentPdfQuery(31337), CancellationToken.None);

        await act.Should().ThrowAsync<KeyNotFoundException>()
            .WithMessage("*31337*");
    }
}
